CREATE VIEW CONSULTA_PRODUCTOS AS
SELECT P.COD_PRODUCTO AS 'CODIGO PRODUCTO', P.NOMBRE, P.PRECIO, P.STOCK, PRO.NOMBRE AS 'NOMBRE PROVEEDOR'
FROM PRODUCTO P INNER JOIN PROVEEDOR PRO
ON P.NIT_PROVEEDOR = PRO.NIT
GO